export default `Turkey is building its own carbon market, and for its exporters the timing is not a coincidence. The EU's CBAM lets importers deduct a carbon price effectively paid in the country of origin, so a Turkish carbon price can keep money in Turkey that would otherwise go to Brussels. This article explains who the Turkish system covers, how it starts, and what it means for companies that are not directly in it.

## The legal basis

Climate Law No. 7552, published in July 2025, provides the legal basis for the Turkish Emissions Trading System. Implementing rules followed; Ember reported that the regulation detailing the system was published on 27 August 2026.

## Who is covered

- **Sectors:** electricity generation, cement, iron and steel, aluminium and fertilisers, chosen to overlap with the EU's CBAM.
- **Size:** installations emitting at least 50,000 tonnes of CO2e a year.

Smaller plants and other sectors are outside the system for now.

## How it starts: a pilot

The first phase is a pilot in 2026 and 2027:

- **2026:** monitoring, reporting and verification only. Installations measure and report their emissions; no allowances are surrendered.
- **2027:** the first year with an obligation. Allowances for 2027 emissions must be surrendered by the last working day of November 2028.
- **Targets:** the system uses product-based benchmarks to reduce emissions intensity, not a national absolute cap.
- **Free allocation:** during the pilot, allowances are allocated free in full, as Eurometal reported, so Turkish producers pay no effective carbon price yet.

## Why it matters for CBAM

An EU importer can claim a CBAM reduction only for a carbon price **effectively paid**, net of free allocation and rebates. With full free allocation in the pilot, there is little or nothing to deduct. Carbon Market Watch has warned that a weak Turkish system would protect neither the climate nor exporters. The deduction becomes meaningful only when Turkish installations pay for a real share of their emissions.

## What covered and uncovered companies should do

- **Covered installations:** the 2026 monitoring year is the time to get measurement right. The same data, verified, also serves CBAM declarations by EU customers.
- **Suppliers to covered installations:** expect requests for data on fuels, electricity and materials you supply.
- **Exporters outside the system:** your EU customers still pay CBAM on default values unless you supply verified actual emissions.

For finance to cut emissions, see [green finance for steel and cement exporters in Turkey](/climate-intelligence/green-finance-steel-cement-turkey) and [CBAM cost for aluminium extruders in Turkey](/climate-intelligence/cbam-cost-aluminium-extrusion-turkey).

This is general guidance. Check the Official Gazette and the Turkish ETS regulation for the current rules.`;
