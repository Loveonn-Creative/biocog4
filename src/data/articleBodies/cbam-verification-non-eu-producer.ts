export default `Under CBAM, a producer outside the EU can save its European customers a great deal of money by replacing EU default values with its own actual emissions. There is one condition: those actual emissions must be verified by an accredited verifier before the importer declares them. Without verification, the importer has to use defaults, which carry a mark-up of 10 percent in 2026, 20 percent in 2027 and 30 percent from 2028.

This article explains how verification works, what the verifier will check, and why starting early matters.

## The timeline

- **24 August 2026:** the European Commission issued guidance on CBAM verification and accreditation.
- **From 1 September 2026:** accredited verifiers can get access to the CBAM Registry.
- **From January 2027:** verification reports can be generated through the Registry.
- **By 30 September 2027:** importers submit the first annual declaration, covering 2026 imports, using verified actual emissions or defaults.

## Who can verify

Verifiers must be accredited for CBAM by a national accreditation body. As of 30 June 2026, one industry tracker reported that 24 EU accreditation bodies had agreed to offer CBAM accreditation, 9 were accepting applications, and only 3 accepted applicants from outside the EU. Large inspection firms were still waiting for accreditation in late September 2026. EU fastener distributors have warned of a severe bottleneck in 2026 because there are too few verifiers for the number of producers worldwide.

## What happens in a verification

1. **A site visit.** Industry guidance says the first verification needs a physical visit to the installation, so the verifier can see the process, the meters and the records. A leaked draft rule would allow virtual visits for some electricity installations; check the final rules.
2. **A check of the monitoring method.** The verifier reviews how you define the installation's boundaries and production processes, which emission sources you include, and how you measure fuel, materials and output.
3. **A check of the data.** The verifier traces the reported numbers back to invoices, meter readings, weighbridge records and laboratory analyses, and tests the calculations.
4. **Precursors.** For products made from purchased inputs, such as rolled steel from purchased slab, the verifier checks the embedded emissions of those precursors and the supplier evidence behind them.
5. **A verification report,** which the importer relies on for its declaration.

## How to prepare

- **Fix the boundary and the method now.** Document which processes produce which CBAM goods, and how emissions are allocated between products.
- **Make every number traceable.** Fuel invoices, electricity bills, material purchases and production records should link to the figures in your emissions report.
- **Get precursor data from your suppliers** with their own installation details.
- **Book a verifier early,** given the shortage, and confirm they are accredited for CBAM and for your sector.

Senseible builds the emissions record from your invoices and bills with each number linked to its source document and the factor and method version recorded, which is the evidence trail a verifier tests. For when verified data pays off, see [CBAM default values versus actual emissions](/climate-intelligence/cbam-default-values-vs-actual-emissions-msme-decision-guide).

This is general guidance. Check the Commission's verification guidance and your verifier's requirements.`;
