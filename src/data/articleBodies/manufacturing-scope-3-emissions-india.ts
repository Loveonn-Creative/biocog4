export default `Manufacturing firms calculate Scope 3 emissions, which are all other indirect emissions in the value chain, by identifying and quantifying raw material extraction and production, supplier emissions, product transportation, employee commuting, waste disposal, and product use and end-of-life.

**The 15 Scope 3 Categories:**
1. Purchased goods and services
2. Capital goods
3. Fuel and energy-related activities
4. Upstream transportation
5. Waste generated in operations
6. Business travel
7. Employee commuting
8. Upstream leased assets
9. Downstream transportation
10. Processing of sold products
11. Use of sold products
12. End-of-life treatment
13. Downstream leased assets
14. Franchises
15. Investments

**India-Specific Considerations:**
- Use India-specific emission factors where available
- Consider informal sector contributions to supply chain
- Account for diverse transportation modes including rail and road

**Prioritization:**
Start with material categories that represent the largest emissions sources, typically purchased goods and upstream transportation for manufacturers.`;
