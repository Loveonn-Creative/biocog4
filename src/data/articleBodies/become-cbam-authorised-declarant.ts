export default `Since 1 January 2026, only an authorised CBAM declarant can import iron and steel, aluminium, cement, fertilisers, hydrogen or electricity into the EU above the 50-tonne exemption. Without the status, customs will not release the goods. For importers this is the gatekeeper step; for exporters, it is worth knowing whether your customer has done it.

This article explains who needs the status, how to apply and what the authority checks.

## Who needs it

- **Importers** of CBAM goods whose imports exceed 50 tonnes a year in total across steel, aluminium, cement and fertilisers, or who import any electricity or hydrogen. See [the 50-tonne exemption](/climate-intelligence/cbam-50-tonne-exemption).
- **Indirect customs representatives** who act as CBAM declarant for an importer, in some cases even below the threshold.

Importers who applied by 31 March 2026 were allowed to keep importing while their application was assessed. Anyone applying now needs the status before importing.

## Where to apply

Applications go through the **CBAM Registry** to the competent authority of the member state where the importer is established. For example:

- **Germany:** DEHSt, the German Emissions Trading Authority.
- **Poland:** KOBiZE, the National Centre for Emissions Management, with checks linked to the customs IT system.
- **Italy:** the Ministry of Environment and Energy Security (MASE), which grants status by numbered decree.

## What the authority checks

The CBAM Regulation sets conditions for authorisation. In summary, the applicant must:

1. **Be established in an EU member state.**
2. **Have no serious or repeated infringements** of customs, tax or market abuse rules, or of CBAM rules.
3. **Show financial and operational capacity** to meet its CBAM obligations, which can include providing a guarantee.

In practice, applicants supply company and customs identification, the expected volume of CBAM goods, and evidence of the systems and people that will handle declarations and certificates.

## After authorisation

The authorised declarant must:

- declare the embedded emissions of its imports each year, the first time by **30 September 2027** for 2026 imports;
- buy CBAM certificates, from **February 2027** for 2026 imports, at the [CBAM certificate price](/climate-intelligence/cbam-certificate-price);
- keep evidence of embedded emissions, either verified actual data from suppliers or EU default values.

## What exporters should take from this

Ask your EU customers whether they are authorised and when they need your emissions data. An authorised importer with a declaration due will prefer suppliers who can provide verified installation data, because it lowers its certificate bill. See [how to get CBAM emissions verified](/climate-intelligence/cbam-verification-non-eu-producer).

This is general guidance, not legal advice. Check your national authority's procedure and the current conditions.`;
