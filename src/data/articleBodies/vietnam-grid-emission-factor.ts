export default `Every factory in Vietnam that reports its carbon footprint, answers a brand's supplier questionnaire or prepares CBAM data needs one number: how much CO2 each unit of grid electricity carries. That number, the grid emission factor, turns kilowatt-hours on the electricity bill into Scope 2 emissions.

## The latest figure

A study by Hanoi University of Science and Technology with the Ministry of Agriculture and Environment put Vietnam's 2024 grid emission factor at **0.681 tonnes of CO2e per megawatt-hour**, or 0.681 kg per kWh. That was 3.2 percent higher than in 2023, because coal-fired generation rose 17.7 percent and made up 49.5 percent of the power mix.

The **official** factor is announced each year by the climate change department of the environment ministry, usually in the first quarter of the following year. When the official figure for a year is published, use it in place of a study estimate, and always state which source and year you used.

## How to use it

Scope 2 emissions from grid electricity, location-based:

**kWh on the bill × grid factor = kg CO2e**

A factory that uses 200,000 kWh in a month: 200,000 × 0.681 = 136,200 kg, or about 136 tonnes of CO2e for that month.

Three points to get right:

1. **Use the factor for the year the electricity was used,** not the latest one, so year-on-year comparisons are fair.
2. **Report location-based and market-based figures separately.** If you buy renewable power through a contract with the right certificates, your market-based figure falls; the location-based figure still uses the grid factor. See [market-based versus location-based Scope 2](/climate-intelligence/scope-2-market-based-vs-location-based-msme-guide).
3. **Rooftop solar you generate and use is not grid electricity.** It reduces the kWh you buy, so it lowers Scope 2 directly.

## Why the number is rising, and why it matters to buyers

A grid that leans more on coal raises the emissions of every kWh, even if a factory's own use stays flat. For exporters, that matters twice: brands reporting their own value-chain emissions see a higher footprint for Vietnamese suppliers, and under CBAM, indirect emissions from electricity count for some products, such as cement and fertilisers. Self-generation and renewable contracts are the main ways to break the link.

Senseible reads electricity bills for units and billing periods, applies the grid factor you specify for the period, and keeps the source of the factor alongside every figure. For Vietnamese buyers' data requests, see [carbon data EU buyers ask Vietnamese textile factories for](/climate-intelligence/vietnam-textile-carbon-footprint-eu-buyers).

Check the environment ministry's official announcement for the factor that applies to your reporting year.`;
