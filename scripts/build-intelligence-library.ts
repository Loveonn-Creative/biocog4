#!/usr/bin/env bun
// Writes supabase/functions/_shared/intelligenceLibrary.generated.ts: the
// public content Biocog Intelligence may cite for general questions.
//   - the answer library (src/data/answerLibrary/*.json: q, short, slug)
//   - the Climate Intelligence article index (titles and excerpts)
//   - the public product facts in docs/seo/brief.md "What Senseible actually does"
// Nothing else from docs/ is read: no runbooks, prompts or internal notes.
// Owner notes, writing instructions, model details and scoring internals are
// removed from the facts. tests/intelligence-evidence.test.ts fails when the
// generated module is out of date.
//
// Usage: bun scripts/build-intelligence-library.ts

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { articleIndex } from '../src/data/articleIndex';
import type { LibraryEntry } from '../supabase/functions/_shared/intelligenceEvidence';

const ROOT = join(import.meta.dir, '..');
const SITE = 'https://senseible.earth';
export const OUT = join(ROOT, 'supabase/functions/_shared/intelligenceLibrary.generated.ts');

const clip = (s: string, n: number) => (s.length > n ? `${s.slice(0, n - 1).trimEnd()}…` : s);

/** The public product facts, without owner notes, instructions or internals. */
export function productFacts(brief: string): string[] {
  const m = /## What Senseible actually does[^\n]*\n([\s\S]*?)\n## /.exec(brief);
  if (!m) return [];
  const out: string[] = [];
  for (const line of m[1].split('\n')) {
    if (!line.startsWith('- ')) continue;
    let s = line.slice(2).trim();
    if (/^plan terms|^verification:/i.test(s)) {
      // Plan terms are not published as instructions; verification keeps only its public meaning.
      if (/^verification:/i.test(s)) out.push('Verification runs rule checks and an evidence gate. Status "Verified" means the rule checks passed, not third-party assurance.');
      continue;
    }
    s = s
      .replace(/,?\s*per the owner/gi, '')
      .replace(/\s*\((?:[^()]*\b(?:owner|white paper|being built)\b[^()]*)\)/gi, '')
      .replace(/,?\s*with an AI vision model[^.]*?(?=\.)/i, '');
    const sentences = s.split(/(?<=\.)\s+/).filter((x) => x && !/\b(never|do not|don't|owner|without the owner)\b/i.test(x));
    s = sentences.join(' ').trim();
    if (s) out.push(s);
  }
  return out;
}

export function buildLibrary(): LibraryEntry[] {
  const dir = join(ROOT, 'src/data/answerLibrary');
  const answers: LibraryEntry[] = readdirSync(dir).filter((f) => f.endsWith('.json')).sort().map((f) => {
    const a = JSON.parse(readFileSync(join(dir, f), 'utf8')) as { slug: string; q: string; short: string };
    return { kind: 'answer', title: a.q, text: clip(a.short, 420), url: `${SITE}/answers/${a.slug}` };
  });
  const articles: LibraryEntry[] = articleIndex.map((a) => ({
    kind: 'article', title: a.title, text: clip(`${a.excerpt} ${a.tags.join(', ')}`, 420), url: `${SITE}/climate-intelligence/${a.slug}`,
  }));
  const facts: LibraryEntry[] = productFacts(readFileSync(join(ROOT, 'docs/seo/brief.md'), 'utf8'))
    .map((text) => ({ kind: 'fact', title: `Senseible platform: ${clip(text.split(/[.:]/)[0], 60)}`, text: clip(text, 600), url: null }));
  return [...facts, ...answers, ...articles];
}

export function renderLibrary(entries: LibraryEntry[]): string {
  // @ts-nocheck: the literal is too large for the type checker (TS2590); the
  // export annotation still gives importers the LibraryEntry[] type.
  return `// @ts-nocheck
// Generated by scripts/build-intelligence-library.ts from public content only
// (answer library, article index, public product facts). Do not edit.
import type { LibraryEntry } from './intelligenceEvidence.ts';

export const INTELLIGENCE_LIBRARY: LibraryEntry[] = ${JSON.stringify(entries, null, 1)};
`;
}

if (import.meta.main) {
  const entries = buildLibrary();
  writeFileSync(OUT, renderLibrary(entries));
  console.log(`intelligence library: ${entries.length} entries`);
}
